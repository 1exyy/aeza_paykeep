import { expect, test } from '@playwright/test'

test('демо открывает реальные экраны клиента и сохраняет действия до обновления страницы', async ({ page }) => {
  await page.route('https://telegram.org/js/telegram-web-app.js?64', (route) => route.fulfill({ body: '' }))
  await page.setViewportSize({ width: 375, height: 740 })
  await page.goto('/payments')
  await expect(page.getByRole('heading', { name: 'Вход' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Aéza PayKeep' })).toBeVisible()
  await page.getByRole('textbox', { name: 'Команда' }).fill('demo')
  await page.getByRole('textbox', { name: 'Логин' }).fill('admin')
  await page.getByLabel('Пароль').fill('demo')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByRole('heading', { name: 'Платежи', exact: true })).toBeVisible()
  await expect(page.getByLabel('Демо · тестовые данные')).toBeVisible()
  await expect(page.getByText('Хостинг проекта')).toBeVisible()
  await page.getByRole('article').filter({ hasText: 'Хостинг проекта' }).getByRole('link', { name: 'Открыть платёж' }).click()
  await expect(page.getByRole('heading', { name: 'Хостинг проекта' })).toBeVisible()
  await page.getByRole('button', { name: 'Отметить оплату' }).click()
  await page.getByLabel('Фактическая дата оплаты').fill('2026-10-20')
  await page.getByRole('button', { name: 'Подтвердить оплату' }).click()
  await expect(page.getByText('Оплачено', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'К списку платежей' }).click()
  await expect(page.getByRole('article').filter({ hasText: 'Хостинг проекта' }).getByText('Оплачено', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Календарь' }).click()
  await expect(page.getByRole('heading', { name: 'Календарь оплат' })).toBeVisible()
  await page.setViewportSize({ width: 320, height: 740 })
  await page.screenshot({ path: 'test-results/calendar-320.png' })
  await page.setViewportSize({ width: 375, height: 740 })
  await page.screenshot({ path: 'test-results/calendar-375.png' })
  await page.getByRole('link', { name: 'Бюджет' }).click()
  await expect(page.getByRole('heading', { name: 'Плановые расходы' })).toBeVisible()
  await page.getByRole('button', { name: 'Ещё' }).click()
  await page.getByRole('dialog', { name: 'Ещё' }).getByRole('link', { name: 'Пользователи' }).click()
  await expect(page.getByRole('heading', { name: 'Пользователи' })).toBeVisible()
  await page.screenshot({ path: 'test-results/demo-users-375.png', fullPage: true })
  await page.getByRole('button', { name: 'Ещё' }).click()
  await page.getByRole('dialog', { name: 'Ещё' }).getByRole('button', { name: 'Выйти' }).click()
  await expect(page.getByRole('heading', { name: 'Вход' })).toBeVisible()
})

test('обычная учётная запись не получает admin-маршруты в демо', async ({ page }) => {
  await page.route('https://telegram.org/js/telegram-web-app.js?64', (route) => route.fulfill({ body: '' }))
  await page.goto('/users')
  await page.getByRole('textbox', { name: 'Команда' }).fill('demo')
  await page.getByRole('textbox', { name: 'Логин' }).fill('anna')
  await page.getByLabel('Пароль').fill('demo')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByRole('heading', { name: 'Нет доступа' })).toBeVisible()
  await page.getByRole('button', { name: 'Ещё' }).click()
  await expect(page.getByRole('dialog', { name: 'Ещё' }).getByRole('link', { name: 'Пользователи' })).toHaveCount(0)
  await page.getByRole('dialog', { name: 'Ещё' }).getByRole('button', { name: 'Выйти' }).click()
  await expect(page.getByRole('heading', { name: 'Вход' })).toBeVisible()
})

test('демо поддерживает создание платежа, вложение и admin-списки', async ({ page }) => {
  await page.route('https://telegram.org/js/telegram-web-app.js?64', (route) => route.fulfill({ body: '' }))
  await page.goto('/recurring-payments')
  await page.getByRole('textbox', { name: 'Команда' }).fill('demo')
  await page.getByRole('textbox', { name: 'Логин' }).fill('admin')
  await page.getByLabel('Пароль').fill('demo')
  await page.getByRole('button', { name: 'Войти' }).click()
  await expect(page.getByRole('heading', { name: 'Регулярные платежи' })).toBeVisible()
  await page.getByRole('link', { name: 'Добавить платёж' }).click()
  await page.getByRole('textbox', { name: 'Название' }).fill('Тестовый сервис')
  await page.getByRole('textbox', { name: 'Сумма' }).fill('50.00')
  await page.getByRole('combobox', { name: 'Валюта *' }).click()
  await page.getByRole('option', { name: 'EUR' }).click()
  await page.getByLabel('Ближайшая дата оплаты').fill('2026-11-10')
  await page.getByRole('button', { name: 'Добавить платёж' }).click()
  await expect(page.getByRole('article').filter({ hasText: 'Тестовый сервис' })).toBeVisible()
  await page.getByRole('link', { name: 'К платежам' }).click()
  await page.getByRole('article').filter({ hasText: 'Тестовый сервис' }).getByRole('link', { name: 'Открыть платёж' }).click()
  await page.getByRole('textbox', { name: 'Адрес ссылки' }).fill('https://example.org/receipt')
  await page.getByRole('button', { name: 'Добавить ссылку' }).click()
  await expect(page.getByText('Ссылка добавлена.')).toBeVisible()
  page.on('dialog', (dialog) => void dialog.accept())
  await page.getByRole('button', { name: 'Удалить' }).click()
  await expect(page.getByRole('heading', { name: 'Вложений пока нет' })).toBeVisible()
  await page.getByRole('button', { name: 'Ещё' }).click()
  await page.getByRole('dialog', { name: 'Ещё' }).getByRole('link', { name: 'Журнал действий' }).click()
  await expect(page.getByRole('heading', { name: 'Журнал действий' })).toBeVisible()
  await page.getByRole('button', { name: 'Ещё' }).click()
  await page.getByRole('dialog', { name: 'Ещё' }).getByRole('link', { name: 'Доставки уведомлений' }).click()
  await expect(page.getByRole('heading', { name: 'Доставки уведомлений' })).toBeVisible()
})
